"""Markdown exporter — assembles the full review package as a .md file."""

from __future__ import annotations

from datetime import datetime, timezone


def build_markdown(
    query: str,
    report_text: str,
    gaps: list[dict],
    papers: list[dict],
    citation_style: str = "apa",
) -> str:
    """
    Assemble the complete Markdown export document.
    """
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines: list[str] = []

    # Title page section
    lines += [
        f"# Literature Review Report",
        f"",
        f"**Query:** {query}",
        f"**Generated:** {now}",
        f"",
        f"> ⚠️ **Disclaimer:** This report was generated by an AI research assistant.",
        f"> Content should be reviewed by a domain expert before use in academic work.",
        f"",
        "---",
        "",
    ]

    # Main review
    lines.append(report_text.strip())
    lines.append("")
    lines.append("---")
    lines.append("")

    # Research gaps summary
    if gaps:
        lines.append("## Research Gaps Summary")
        lines.append("")
        for gap in gaps:
            lines.append(f"### {gap.get('gap_index', '')}. {gap.get('title', '')}")
            lines.append("")
            lines.append(gap.get("explanation", ""))
            lines.append("")

    # Comparison table
    if papers:
        lines.append("## Paper Comparison Table")
        lines.append("")
        lines.append(
            "| # | Title | Year | Methodology | Datasets | Key Metrics | Relevance |"
        )
        lines.append("|---|-------|------|------------|----------|-------------|-----------|")
        for i, p in enumerate(papers, 1):
            title = p.get("title", "")[:60]
            year = str(p.get("year") or "")
            method = (p.get("methodology") or "")[:40]
            datasets = "; ".join(d["name"] for d in (p.get("datasets") or [])[:2])
            metrics = "; ".join(
                f"{m['name']}={m['value']}" for m in (p.get("metrics") or [])[:2]
            )
            score = f"{p.get('relevance_score', 0):.2f}" if p.get("relevance_score") else ""
            lines.append(f"| {i} | {title} | {year} | {method} | {datasets} | {metrics} | {score} |")
        lines.append("")

    # Reference list
    lines.append("## References")
    lines.append("")
    citation_key = f"citation_{citation_style}"
    for i, paper in enumerate(papers, 1):
        cite = paper.get(citation_key) or paper.get("citation_apa") or paper.get("title", "")
        lines.append(f"{i}. {cite}")
    lines.append("")

    return "\n".join(lines)
